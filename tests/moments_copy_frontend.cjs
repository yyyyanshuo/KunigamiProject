const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'templates/moments.html'), 'utf8');
const start = source.indexOf("const copyBtn = e.target.closest('.btn-copy-moment');");
const end = source.indexOf('\n                });', start);
assert(start >= 0 && end > start);
const handler = source.slice(start, end);
const disclosure = fs.readFileSync(path.join(root, 'static/ai-disclosure.js'), 'utf8');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'static/locales/ui.json'), 'utf8'));

async function copy(moment, language = 'zh-CN') {
    const writes = [];
    const card = {}, button = {textContent: 'Copy', closest: () => card};
    const context = {
        window: {location: {origin: 'https://saki.test'}},
        document: {documentElement: {dataset: {}}},
        navigator: {clipboard: {writeText: async text => {writes.push(text);}}},
        e: {target: {closest: () => button}},
        findMomentFromCard: value => {assert.equal(value, card); return moment;},
        formatTime: value => value,
        SakiI18n: {t: key => catalog[key]?.[language] || key},
        showToast() {}, setTimeout() {},
    };
    vm.createContext(context);
    vm.runInContext(disclosure + '\n(function(e){' + handler + '})(e);', context);
    await new Promise(setImmediate);
    assert.equal(writes.length, 1);
    return writes[0];
}

const post = {
    remark: '作者', content: '原文 [TRANSFER:100€|Pour tes cafés.]', timestamp: '2026-10-29 12:00:00',
    liker_remarks: ['点赞者'], comments: [{remark: '评论者', reply_to_remark: '作者', content: '留言'}],
    blocked_character_ids: ['a', 'b'],
    blocked_characters: [{id: 'a', name: '角色备注'}, {id: 'b', name: '<b>角色名</b>'}],
};

for (const language of ['zh-CN', 'en', 'ja']) {
    test(`copy includes blocked names with ${language} label and preserves post details`, async () => {
        const text = await copy(post, language);
        assert(text.includes(`【${catalog['谁不可见'][language]}】角色备注、<b>角色名</b>\n`));
        assert(text.includes(`【朋友圈】作者：${post.content}。（${post.timestamp}）`));
        assert(text.includes('【点赞】点赞者\n【评论】\n评论者：回复 作者：留言'));
        assert(text.endsWith('——\nGenerated by Saki AI\nhttps://saki.test'));
    });
}

test('blocked IDs are authoritative, deduplicated, and fall back to missing character IDs', async () => {
    const text = await copy({...post, blocked_character_ids: ['b', 'b', 'deleted']});
    assert(text.includes('【谁不可见】<b>角色名</b>、deleted\n'));
    assert(!text.includes('角色备注'));
});

test('public and legacy posts omit the visibility line even with stale names', async () => {
    for (const ids of [[], undefined]) {
        const text = await copy({...post, blocked_character_ids: ids});
        assert(!text.includes('【谁不可见】'));
        assert(text.includes(post.content));
    }
});
